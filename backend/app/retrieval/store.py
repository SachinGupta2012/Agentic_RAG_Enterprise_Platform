"""Qdrant-backed hybrid retrieval store.

Only the retrieval split is ever written to this collection. Embeddings are
generated by Qdrant Cloud Inference; no embedding model or vector database runs
on the application host.
"""

from __future__ import annotations

import logging
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Literal

import httpx
from qdrant_client import QdrantClient, models
from qdrant_client.http.exceptions import ResponseHandlingException, UnexpectedResponse
from tenacity import retry, retry_if_exception, stop_after_attempt, wait_exponential

from app.core.config import Settings, get_settings
from app.retrieval.pii import RedactionCounts, redact_pii
from app.retrieval.schemas import (
    RetrievalFilters,
    RetrievalHealthResponse,
    RetrievalHit,
    RetrievalSearchRequest,
    RetrievalSearchResponse,
)

logger = logging.getLogger(__name__)

# Default dense vector size. Override with QDRANT_DENSE_VECTOR_SIZE when the
# configured inference model emits a different dimension.
DENSE_VECTOR_SIZE = 384
PAYLOAD_INDEXES: dict[str, Any] = {
    "category": models.PayloadSchemaType.KEYWORD,
    "department": models.PayloadSchemaType.KEYWORD,
    "priority": models.PayloadSchemaType.KEYWORD,
    "language": models.PayloadSchemaType.KEYWORD,
    "resolution_status": models.PayloadSchemaType.KEYWORD,
    "source_dataset": models.PayloadSchemaType.KEYWORD,
    "source_ticket_id": models.PayloadSchemaType.KEYWORD,
    "tags": models.PayloadSchemaType.KEYWORD,
    "source_row_index": models.PayloadSchemaType.INTEGER,
}


class RetrievalError(Exception):
    """Base class for retrieval failures."""


class RetrievalNotConfigured(RetrievalError):
    """Qdrant credentials are missing."""


class RetrievalCollectionMissing(RetrievalError):
    """The configured collection has not been created yet."""


class RetrievalUnavailable(RetrievalError):
    """Qdrant could not be reached or returned an unexpected error."""


class RetrievalDimensionMismatch(RetrievalError):
    """The configured dense dimension does not match the stored collection."""


@dataclass(frozen=True)
class TicketDocument:
    """A redacted ticket ready to be embedded and stored."""

    ticket_id: str
    source_ticket_id: str
    subject: str
    customer_query: str
    agent_response: str
    category: str
    department: str
    priority: str
    language: str
    tags: tuple[str, ...]
    resolution_status: str
    source_dataset: str
    source_row_index: int | None
    source_version: str | None
    dense_text: str
    sparse_text: str
    display_text: str
    pii_redactions: RedactionCounts


def _snippet(text: str, max_chars: int = 320) -> str:
    normalized = " ".join(text.split())
    if len(normalized) <= max_chars:
        return normalized
    cut = normalized[:max_chars].rsplit(" ", 1)[0].rstrip(" ,.;:-")
    return f"{cut}..."


def build_filter(filters: RetrievalFilters) -> models.Filter | None:
    """Translate API filters into a Qdrant filter."""

    conditions: list[models.FieldCondition] = []
    for field_name in ("category", "department", "priority", "language"):
        value = getattr(filters, field_name)
        if value:
            conditions.append(
                models.FieldCondition(
                    key=field_name,
                    match=models.MatchValue(value=value),
                )
            )
    return models.Filter(must=conditions) if conditions else None


def build_point(
    document: TicketDocument,
    *,
    dense_model: str,
    sparse_model: str,
    dense_vector: str,
    sparse_vector: str,
) -> models.PointStruct:
    """Build a Qdrant point with server-side dense and sparse inference."""

    payload: dict[str, Any] = {
        "ticket_id": document.ticket_id,
        "source_ticket_id": document.source_ticket_id,
        "source_dataset": document.source_dataset,
        "source_row_index": document.source_row_index,
        "source_version": document.source_version,
        "source_has_native_id": False,
        "source_ticket_id_kind": "derived_locator",
        "subject": document.subject,
        "customer_query": document.customer_query,
        "agent_response": document.agent_response,
        "text": document.display_text,
        "category": document.category,
        "department": document.department,
        "priority": document.priority,
        "language": document.language,
        "tags": list(document.tags),
        "resolution_status": document.resolution_status,
        "pii_redactions": document.pii_redactions.as_dict(),
        "schema_version": "phase2-v1",
        "split": "retrieval",
    }

    return models.PointStruct(
        id=document.ticket_id,
        vector={
            dense_vector: models.Document(text=document.dense_text, model=dense_model),
            sparse_vector: models.Document(text=document.sparse_text, model=sparse_model),
        },
        payload=payload,
    )


def _is_retryable(exc: BaseException) -> bool:
    if isinstance(exc, (ResponseHandlingException, httpx.TransportError, TimeoutError)):
        return True
    if isinstance(exc, UnexpectedResponse):
        status = getattr(exc, "status_code", None)
        return status == 429 or (isinstance(status, int) and status >= 500)
    return False


def _log_retry(retry_state: Any) -> None:
    exc = retry_state.outcome.exception() if retry_state.outcome else None
    logger.warning(
        "Qdrant request failed (attempt %s); retrying: %s",
        retry_state.attempt_number,
        type(exc).__name__ if exc else "unknown",
    )


class QdrantTicketStore:
    """Thin synchronous wrapper around a Qdrant collection."""

    def __init__(
        self,
        settings: Settings | None = None,
        client: QdrantClient | None = None,
        collection_name: str | None = None,
    ) -> None:
        self._settings = settings or get_settings()
        self._client = client
        self._collection = collection_name or self._settings.qdrant_collection

    @property
    def settings(self) -> Settings:
        """Return the store settings."""

        return self._settings

    @property
    def collection_name(self) -> str:
        """Return the active collection name."""

        return self._collection

    @property
    def client(self) -> QdrantClient:
        """Return a lazily created Qdrant client."""

        if self._client is None:
            self._client = self._create_client()
        return self._client

    def _create_client(self) -> QdrantClient:
        url = self._settings.qdrant_url.strip()
        api_key = self._settings.qdrant_api_key_value.strip()
        if not url or not api_key:
            raise RetrievalNotConfigured(
                "Qdrant is not configured. Set QDRANT_URL and QDRANT_API_KEY in .env."
            )
        try:
            return QdrantClient(
                url=url,
                api_key=api_key,
                cloud_inference=True,
                timeout=self._settings.retrieval_timeout_seconds,
            )
        except Exception as exc:  # pragma: no cover - constructor failures are environmental
            raise RetrievalUnavailable("Could not initialize the Qdrant client.") from exc

    def ensure_collection(self, recreate: bool = False) -> None:
        """Create the collection and payload indexes when needed."""

        client = self.client
        exists = client.collection_exists(self._collection)
        if recreate and exists:
            logger.info("Deleting existing collection %s", self._collection)
            client.delete_collection(self._collection)
            exists = False

        if not exists:
            logger.info("Creating collection %s", self._collection)
            client.create_collection(
                collection_name=self._collection,
                vectors_config={
                    self._settings.qdrant_dense_vector: models.VectorParams(
                        size=self._settings.qdrant_dense_vector_size,
                        distance=models.Distance.COSINE,
                    ),
                },
                sparse_vectors_config={
                    self._settings.qdrant_sparse_vector: models.SparseVectorParams(),
                },
            )

        self._ensure_payload_indexes()
        self.validate_collection_dimensions()

    def validate_collection_dimensions(self) -> int:
        """Fail fast when the configured dense size differs from the collection."""

        info = self.client.get_collection(self._collection)
        vectors = info.config.params.vectors
        if isinstance(vectors, Mapping):
            params = vectors.get(self._settings.qdrant_dense_vector)
        else:
            params = vectors

        if params is None:
            raise RetrievalDimensionMismatch(
                f"Collection {self._collection!r} has no dense vector named "
                f"{self._settings.qdrant_dense_vector!r}."
            )

        actual = int(params.size)
        expected = self._settings.qdrant_dense_vector_size
        if actual != expected:
            raise RetrievalDimensionMismatch(
                f"Configured dense size {expected} does not match collection "
                f"{self._collection!r} size {actual}. Update "
                "QDRANT_DENSE_VECTOR_SIZE or re-index with a matching model."
            )
        return actual

    def _ensure_payload_indexes(self) -> None:
        info = self.client.get_collection(self._collection)
        existing = set((info.payload_schema or {}).keys())
        for field_name, schema in PAYLOAD_INDEXES.items():
            if field_name in existing:
                continue
            logger.info("Creating payload index on %s", field_name)
            self.client.create_payload_index(
                collection_name=self._collection,
                field_name=field_name,
                field_schema=schema,
                wait=True,
            )

    def count(self) -> int:
        """Return the exact number of stored points."""

        result = self.client.count(collection_name=self._collection, exact=True)
        return int(result.count)

    def delete_collection(self) -> None:
        """Delete the active collection if it exists."""

        if self.client.collection_exists(self._collection):
            self.client.delete_collection(self._collection)

    def health(self) -> RetrievalHealthResponse:
        """Return readiness details without leaking credentials."""

        try:
            if not self.client.collection_exists(self._collection):
                raise RetrievalCollectionMissing(
                    "Retrieval index is not ready. Run scripts/ingest_qdrant.py."
                )
            self.validate_collection_dimensions()
            count = self.count()
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalUnavailable("Retrieval service is unavailable.") from exc

        return RetrievalHealthResponse(
            status="ok",
            collection=self._collection,
            document_count=count,
            dense_model=self._settings.qdrant_dense_model,
            sparse_model=self._settings.qdrant_sparse_model,
        )

    @retry(
        retry=retry_if_exception(_is_retryable),
        wait=wait_exponential(multiplier=2, min=2, max=30),
        stop=stop_after_attempt(5),
        before_sleep=_log_retry,
        reraise=True,
    )
    def _upsert_batch(self, points: Sequence[models.PointStruct]) -> None:
        self.client.upsert(
            collection_name=self._collection,
            points=list(points),
            wait=True,
        )

    def upsert_documents(
        self,
        documents: Sequence[TicketDocument],
        batch_size: int | None = None,
    ) -> int:
        """Embed and upsert documents in small batches."""

        size = batch_size or self._settings.retrieval_batch_size
        if size < 1:
            raise ValueError("batch_size must be at least 1")

        written = 0
        for start in range(0, len(documents), size):
            batch = documents[start : start + size]
            points = [
                build_point(
                    document,
                    dense_model=self._settings.qdrant_dense_model,
                    sparse_model=self._settings.qdrant_sparse_model,
                    dense_vector=self._settings.qdrant_dense_vector,
                    sparse_vector=self._settings.qdrant_sparse_vector,
                )
                for document in batch
            ]
            self._upsert_batch(points)
            written += len(points)
            logger.info(
                "Upserted %s/%s documents into %s",
                written,
                len(documents),
                self._collection,
            )
        return written

    def fetch_payloads(
        self,
        ids: Sequence[str],
        batch_size: int | None = None,
    ) -> dict[str, dict[str, Any]]:
        """Fetch stored payloads by point ID without reading vectors."""

        size = batch_size or self._settings.retrieval_batch_size
        if size < 1:
            raise ValueError("batch_size must be at least 1")

        payloads: dict[str, dict[str, Any]] = {}
        try:
            for start in range(0, len(ids), size):
                batch = list(ids[start : start + size])
                points = self.client.retrieve(
                    collection_name=self._collection,
                    ids=batch,
                    with_payload=True,
                    with_vectors=False,
                )
                for point in points:
                    payloads[str(point.id)] = dict(point.payload or {})
        except UnexpectedResponse as exc:
            if getattr(exc, "status_code", None) == 404:
                raise RetrievalCollectionMissing(
                    "Retrieval index is not ready. Run scripts/ingest_qdrant.py."
                ) from exc
            raise RetrievalUnavailable("Retrieval service is unavailable.") from exc
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalUnavailable("Retrieval service is unavailable.") from exc
        return payloads

    def search(self, request: RetrievalSearchRequest) -> RetrievalSearchResponse:
        """Run dense, sparse, or hybrid retrieval depending on the request mode."""

        query, query_counts = redact_pii(request.query)
        query_filter = build_filter(request.filters)
        started = time.perf_counter()
        score_type: Literal["rrf", "dense", "sparse"]
        retrieval_mode: Literal["dense", "sparse", "hybrid_rrf"]

        try:
            if request.mode == "hybrid":
                points = self._hybrid_points(query, query_filter, request)
                score_type = "rrf"
                retrieval_mode = "hybrid_rrf"
            else:
                points = self._single_points(query, query_filter, request, request.mode)
                score_type = request.mode
                retrieval_mode = request.mode
        except UnexpectedResponse as exc:
            if getattr(exc, "status_code", None) == 404:
                raise RetrievalCollectionMissing(
                    "Retrieval index is not ready. Run scripts/ingest_qdrant.py."
                ) from exc
            raise RetrievalUnavailable("Retrieval service is unavailable.") from exc
        except RetrievalError:
            raise
        except Exception as exc:
            raise RetrievalUnavailable("Retrieval service is unavailable.") from exc

        latency_ms = round((time.perf_counter() - started) * 1000, 2)
        hits = [self._to_hit(point, score_type) for point in points]
        warnings: list[str] = []
        if query_counts.total:
            warnings.append("Query contained PII patterns; they were redacted before embedding.")

        return RetrievalSearchResponse(
            query=query,
            hits=hits,
            count=len(hits),
            retrieval_mode=retrieval_mode,
            dense_model=self._settings.qdrant_dense_model,
            sparse_model=self._settings.qdrant_sparse_model,
            collection=self._collection,
            latency_ms=latency_ms,
            query_pii_redactions=query_counts.as_dict(),
            warnings=warnings,
        )

    def _hybrid_points(
        self,
        query: str,
        query_filter: models.Filter | None,
        request: RetrievalSearchRequest,
    ) -> Sequence[Any]:
        """Dense + BM25 prefetches fused with RRF."""

        prefetch_limit = request.prefetch_limit or self._settings.retrieval_prefetch_limit
        response = self.client.query_points(
            collection_name=self._collection,
            prefetch=[
                models.Prefetch(
                    query=models.Document(
                        text=query,
                        model=self._settings.qdrant_dense_model,
                    ),
                    using=self._settings.qdrant_dense_vector,
                    filter=query_filter,
                    limit=prefetch_limit,
                ),
                models.Prefetch(
                    query=models.Document(
                        text=query,
                        model=self._settings.qdrant_sparse_model,
                    ),
                    using=self._settings.qdrant_sparse_vector,
                    filter=query_filter,
                    limit=prefetch_limit,
                ),
            ],
            query=models.RrfQuery(rrf=models.Rrf(k=self._settings.retrieval_rrf_k)),
            query_filter=query_filter,
            limit=request.top_k,
            with_payload=True,
            with_vectors=False,
        )
        return response.points

    def _single_points(
        self,
        query: str,
        query_filter: models.Filter | None,
        request: RetrievalSearchRequest,
        mode: str,
    ) -> Sequence[Any]:
        """Dense-only or BM25-only retrieval without fusion."""

        if mode == "dense":
            using = self._settings.qdrant_dense_vector
            model = self._settings.qdrant_dense_model
        else:
            using = self._settings.qdrant_sparse_vector
            model = self._settings.qdrant_sparse_model

        response = self.client.query_points(
            collection_name=self._collection,
            query=models.Document(text=query, model=model),
            using=using,
            query_filter=query_filter,
            limit=request.top_k,
            with_payload=True,
            with_vectors=False,
        )
        return response.points

    def _to_hit(self, point: Any, score_type: Literal["rrf", "dense", "sparse"]) -> RetrievalHit:
        payload: Mapping[str, Any] = point.payload or {}
        subject = str(payload.get("subject") or "")
        customer_query = str(payload.get("customer_query") or payload.get("text") or "")
        agent_response = str(payload.get("agent_response") or "")

        tags_value = payload.get("tags") or []
        tags = [str(tag) for tag in tags_value] if isinstance(tags_value, list) else []

        redactions_value = payload.get("pii_redactions") or {}
        redactions = (
            {
                str(key): int(value)
                for key, value in redactions_value.items()
                if isinstance(value, int)
            }
            if isinstance(redactions_value, Mapping)
            else {}
        )

        source_row_index = payload.get("source_row_index")
        if not isinstance(source_row_index, int):
            source_row_index = None

        source_version = payload.get("source_version")
        if not isinstance(source_version, str) or not source_version:
            source_version = None

        resolution_snippet = _snippet(agent_response) if agent_response else None

        return RetrievalHit(
            ticket_id=str(payload.get("ticket_id") or point.id),
            score=float(point.score),
            score_type=score_type,
            subject=subject,
            snippet=_snippet(customer_query),
            resolution_snippet=resolution_snippet,
            category=_optional_str(payload.get("category")),
            department=_optional_str(payload.get("department")),
            priority=_optional_str(payload.get("priority")),
            language=_optional_str(payload.get("language")),
            tags=tags,
            source_ticket_id=_optional_str(payload.get("source_ticket_id")),
            source_dataset=_optional_str(payload.get("source_dataset")),
            source_row_index=source_row_index,
            source_version=source_version,
            pii_redactions=redactions,
        )

    def close(self) -> None:
        """Close the underlying HTTP client."""

        if self._client is not None:
            self._client.close()
            self._client = None


def _optional_str(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None
